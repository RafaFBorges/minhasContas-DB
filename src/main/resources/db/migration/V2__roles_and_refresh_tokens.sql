-- Papéis: SYSTEM > ADMIN > SUPPORT > USER. Todos os usuários existentes viram USER; a conta de serviço vira SYSTEM
alter table users add column role varchar(20) not null default 'USER';
-- Só a conta de serviço exata: é a que o UserInitialDataEnsurer gerencia. Outras grafias não podem mais ser cadastradas
-- (Register as recusa); numa base legada que tenha uma, ela segue como conta comum
update users set role = 'SYSTEM' where username = 'System';

-- Refresh tokens: só o hash (SHA-256 em hexadecimal) é guardado, nunca o token. revoked_at preenchido = já usado ou encerrado
create table refresh_tokens (
  id bigint generated by default as identity,
  user_id bigint not null,
  token_hash varchar(64) not null unique,
  -- Uma cadeia = um login e todas as suas rotações. O logout encerra a cadeia; chain_started_at limita a vida total dela
  chain_id uuid not null,
  chain_started_at timestamp(6) with time zone not null,
  created_at timestamp(6) with time zone not null,
  expires_at timestamp(6) with time zone not null,
  revoked_at timestamp(6) with time zone,
  primary key (id),
  constraint fk_refresh_tokens_user foreign key (user_id) references users (id) on delete cascade
);
create index idx_refresh_tokens_user on refresh_tokens (user_id);
create index idx_refresh_tokens_chain on refresh_tokens (chain_id);
-- A limpeza periódica filtra por estas duas colunas (expires_at < agora ou revoked_at < limite)
create index idx_refresh_tokens_expires_at on refresh_tokens (expires_at);
create index idx_refresh_tokens_revoked_at on refresh_tokens (revoked_at) where revoked_at is not null;
